/// True when `name` is an `IpcApi` method — the authoritative `cmd.<name>` key
/// test. `KNOWN_CMDS` is sorted, so this is a binary search, not a scan: it runs
/// once per `ipc.result` record inside `log_append` (§11 keeps that path cheap).
pub(super) fn is_known_cmd(name: &str) -> bool {
    KNOWN_CMDS.binary_search(&name).is_ok()
}

