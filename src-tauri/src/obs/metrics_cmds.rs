//! P91 §8 — the `cmd.<name>` metric-key ALLOW-LIST: the exact set of `IpcApi`
//! method names.
//!
//! Audit F3: `log_append` carries `ipc.result` records straight from the webview,
//! and each one's `cmd` becomes a durable `cmd.<name>` histogram key in
//! `usage.json`. A SHAPE predicate (`metrics_keys::is_valid_cmd_name`) cannot
//! bound that — any well-shaped string passes — so membership in the real
//! command set is what decides. An unknown name drops the observation.
//!
//! GENERATED from the `IpcApi` interface declarations
//! (`src/ipc/types/ipc-api.ts`, `ipc-api-forge.ts`, `ipc-api-obs.ts`), which is
//! the set the frontend proxy can emit: `obs/ipcProxy.ts` uses the METHOD NAME as
//! `cmd`, so these are camelCase, not the snake_case Tauri command names.
//! `tests_metrics_cmds.rs` re-derives the list from those `.ts` files at test
//! time and fails on any drift, so adding an IPC method without regenerating this
//! table is caught by `cargo test`, not by a silently missing histogram.
//!
//! The §2.3-excluded methods (`logAppend`, `metricsSnapshot`, …) are present for
//! that exact-mirror property; the proxy never instruments them, so they can
//! never actually arrive.

